#!/usr/bin/env python3
"""Probe Chutes for the reasoning_effort values each model accepts.

The public catalog does not publish the allowed effort menu. Sending a
deliberately invalid value makes the OpenAI-compatible gateway answer with the
accepted literals, for example:

    'reasoning_effort' must be one of: 'low', 'high', 'max'

This script reads /v1/models, probes every row once, and can regenerate the
static Rust snapshot consumed by chutes-build-core. It is a development tool:
no API key is written anywhere, and CI never runs it.

Usage:
    CHUTES_API_KEY=cpk_... python scripts/probe_reasoning_efforts.py
    CHUTES_API_KEY=cpk_... python scripts/probe_reasoning_efforts.py --write
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

CATALOG_URL = "https://llm.chutes.ai/v1/models"
CHAT_URL = "https://llm.chutes.ai/v1/chat/completions"
EFFORT_TOKENS = (
    "none",
    "minimal",
    "low",
    "medium",
    "high",
    "xhigh",
    "max",
    "ultra",
)
TOKEN_ORDER = {token: index for index, token in enumerate(EFFORT_TOKENS)}
SNAPSHOT_PATH = Path(
    "crates/chutes-build-core/src/reasoning_efforts_snapshot.rs"
)


def api_key() -> str:
    key = os.environ.get("CHUTES_API_KEY", "").strip()
    if not key:
        raise SystemExit("CHUTES_API_KEY is required")
    return key


def request_json(url: str, key: str, payload: dict | None = None) -> dict:
    data = json.dumps(payload).encode() if payload is not None else None
    request = urllib.request.Request(
        url,
        data=data,
        headers={
            "Authorization": f"Bearer {key}",
            "Content-Type": "application/json",
        },
        method="POST" if data is not None else "GET",
    )
    with urllib.request.urlopen(request, timeout=120) as response:
        return json.loads(response.read().decode("utf-8", "replace"))


def parse_allowed(text: str) -> list[str]:
    """Extract known effort tokens from a validation message, ordered."""
    found = set()
    for value in re.findall(r"'([a-z]+)'", text.lower()):
        if value in TOKEN_ORDER:
            found.add(value)
    return sorted(found, key=lambda value: TOKEN_ORDER[value])


def probe(model: str, key: str) -> tuple[list[str], str]:
    payload = {
        "model": model,
        "messages": [{"role": "user", "content": "hi"}],
        "max_tokens": 1,
        "reasoning_effort": "__probe__",
    }
    last_error = ""
    for attempt in range(4):
        try:
            request_json(CHAT_URL, key, payload)
            return [], "accepted-invalid-value"
        except urllib.error.HTTPError as error:
            body = error.read().decode("utf-8", "replace")
            allowed = parse_allowed(body)
            if allowed:
                return allowed, ""
            if error.code in (429, 500, 502, 503, 504) and attempt < 3:
                last_error = f"HTTP {error.code}"
                time.sleep(2 * (attempt + 1))
                continue
            return [], f"HTTP {error.code}: {body[:180]}"
        except Exception as error:  # noqa: BLE001 - report the probe failure
            last_error = f"{type(error).__name__}: {error}"
            time.sleep(2 * (attempt + 1))
    return [], last_error


def rust_snapshot(rows: dict[str, list[str]], catalog_size: int) -> str:
    lines = [
        "// @generated by scripts/probe_reasoning_efforts.py; do not edit by hand.",
        f"// Probed {dt.datetime.now(dt.timezone.utc).isoformat()} from "
        f"{catalog_size} catalogue rows. Update with the script above.",
        "",
        "/// Per-model reasoning_effort values accepted by the live Chutes gateway.",
        "pub(crate) static EFFORT_SNAPSHOT: &[(&str, &[&str])] = &[",
    ]
    for model, values in rows.items():
        rendered = ", ".join(f'"{value}"' for value in values)
        lines.append(f'    ("{model}", &[{rendered}]),')
    lines.extend(["];", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--write",
        action="store_true",
        help=f"write the Rust snapshot to {SNAPSHOT_PATH}",
    )
    args = parser.parse_args()
    key = api_key()

    catalog = request_json(CATALOG_URL, key).get("data", [])
    rows: dict[str, list[str]] = {}
    skipped: dict[str, str] = {}
    for entry in catalog:
        model = entry.get("id") or entry.get("model")
        if not model:
            continue
        allowed, reason = probe(model, key)
        if allowed:
            rows[model] = allowed
            print(f"{model}: {', '.join(allowed)}")
        else:
            skipped[model] = reason
            print(f"{model}: skipped ({reason})")

    if args.write:
        SNAPSHOT_PATH.write_text(rust_snapshot(rows, len(catalog)), encoding="utf-8")
        print(f"wrote {SNAPSHOT_PATH} ({len(rows)} models)")
    else:
        print(json.dumps(rows, indent=2))
    if skipped:
        print(f"skipped {len(skipped)} models", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
